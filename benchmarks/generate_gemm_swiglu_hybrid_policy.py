#!/usr/bin/env python3
"""Generate a conservative GEMM+SwiGLU hybrid policy from crossover CSVs."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path


def load(path: Path) -> dict[tuple[int, int, int], float]:
    out: dict[tuple[int, int, int], float] = {}
    with path.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["variant"] != "v4_cublas":
                continue
            key = (int(row["m"]), int(row["k"]), int(row["n"]))
            out[key] = float(row["custom_speedup"])
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("inputs", nargs="+", type=Path)
    p.add_argument("--threshold", type=float, default=1.05)
    p.add_argument("--header", type=Path, required=True)
    args = p.parse_args()

    by_shape: dict[tuple[int, int, int], list[float]] = defaultdict(list)
    for path in args.inputs:
        for shape, speedup in load(path).items():
            by_shape[shape].append(speedup)

    runs = len(args.inputs)
    accepted = {
        shape
        for shape, vals in by_shape.items()
        if len(vals) == runs and all(v >= args.threshold for v in vals)
    }

    ms = sorted({m for m, _, _ in by_shape})
    ks = sorted({k for _, k, _ in by_shape})
    ns = sorted({n for _, _, n in by_shape})

    best: tuple[int, int, int, int] | None = None
    for max_m in ms:
        for max_k in ks:
            for max_n in ns:
                inside = {
                    shape
                    for shape in by_shape
                    if shape[0] <= max_m and shape[1] <= max_k and shape[2] <= max_n
                }
                if not inside or not inside.issubset(accepted):
                    continue
                score = len(inside)
                candidate = (score, max_m, max_k, max_n)
                if best is None or candidate > best:
                    best = candidate

    if best is None:
        raise SystemExit("no conservative rectangular custom region found")

    _, max_m, max_k, max_n = best
    header = f"""#pragma once

#include <cstdint>

// Generated by benchmarks/generate_gemm_swiglu_hybrid_policy.py
// Acceptance gate: custom V7 speedup >= {args.threshold:.3f}x in all {runs} runs.
namespace cuda_operator_lab::generated {{

constexpr std::uint64_t kGemmSwiGluCustomMaxM = {max_m}ULL;
constexpr std::uint64_t kGemmSwiGluCustomMaxK = {max_k}ULL;
constexpr std::uint64_t kGemmSwiGluCustomMaxN = {max_n}ULL;

inline bool gemm_swiglu_use_custom_v7(
    std::uint64_t m,
    std::uint64_t k,
    std::uint64_t n) {{
  return m <= kGemmSwiGluCustomMaxM &&
         k <= kGemmSwiGluCustomMaxK &&
         n <= kGemmSwiGluCustomMaxN &&
         (m % 16ULL) == 0ULL &&
         (k % 16ULL) == 0ULL &&
         (n % 64ULL) == 0ULL;
}}

}}  // namespace cuda_operator_lab::generated
"""
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding="utf-8")
    print(f"generated M<={max_m}, K<={max_k}, N<={max_n} from {len(by_shape)} shapes")


if __name__ == "__main__":
    main()
